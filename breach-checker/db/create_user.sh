#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE ${POSTGRES_READ_ONLY_USER} LOGIN PASSWORD '${APP_DB_PASSWORD}';
    GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO ${POSTGRES_READ_ONLY_USER};
    GRANT SELECT ON TABLE leaked_hashes TO ${POSTGRES_READ_ONLY_USER};
EOSQL